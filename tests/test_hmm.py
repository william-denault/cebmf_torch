def test_rna_style_fit_with_missing_entries():
    generator = torch.Generator().manual_seed(19)
    loading = (torch.arange(12) > 3).double()
    factor = torch.cat((torch.zeros(10), torch.ones(20) * 2, torch.zeros(10))).double()
    y = loading[:, None] * factor + 0.1 * torch.randn(12, 40, generator=generator, dtype=torch.float64)
    y[1, 4] = y[5, 21] = torch.nan
    y[:, 15] = torch.nan
    model = cEBMF(
        y,
        K=1,
        prior_L="gbinary",
        prior_F="hmm_pos",
        device=torch.device("cpu"),
        prior_F_kwargs={"maxiter": 8, "penalty": 1.5},
        allow_backfitting=False,
    )
    model.initialise_factors(L=loading[:, None], F=factor[:, None])
    model.fit(3)
    assert torch.isfinite(model.F).all() and torch.isfinite(model.L).all()
    assert (model.F >= 0).all() and all(math.isfinite(obj) for obj in model.obj)
    assert model.F[10:30].mean() > model.F[:10].mean() + 0.5


