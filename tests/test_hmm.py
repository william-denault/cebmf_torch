@pytest.mark.parametrize("side", ["L", "F"])
@pytest.mark.parametrize("prior", ["hmm", "hmm_pos", "hmm_neg"])
def test_registry_cebmf_ignores_covariates_once(side, prior):
    y = torch.arange(1, 97, dtype=torch.float64).reshape(8, 12) / 96
    settings = {
        "mu": [0, -1] if prior == "hmm_neg" else [0, 1],
        "prior_sd": [0, 0.4],
        "maxiter": 3,
        "penalty": 1.5,
    }
    kwargs = {f"prior_{side}": prior, f"prior_{side}_kwargs": settings}
    # Even malformed side information is ignored before device/shape handling.
    external = {f"X_{side.lower()}": tensor([math.nan]), "self_row_cov" if side == "L" else "self_col_cov": True}
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        model = cEBMF(y, K=1, S=1, device=torch.device("cpu"), allow_backfitting=False, **kwargs, **external)
        model.initialise_factors()
        model.fit(2)
    messages = [str(w.message) for w in caught if "HMM specified" in str(w.message)]
    assert len(messages) == 1 and f"for {side}" in messages[0]
    assert "'emdn' or 'spiked_emdn'" in messages[0]
    assert getattr(model.covariate, f"X_{side.lower()}") is None
    plain = cEBMF(y, K=1, S=1, device=torch.device("cpu"), allow_backfitting=False, **kwargs)
    plain.initialise_factors()
    plain.fit(2)
    torch.testing.assert_close(model.F, plain.F)
    torch.testing.assert_close(model.L, plain.L)
    assert all(math.isfinite(value) for value in model.obj)
    factor = getattr(model, side)
    if prior == "hmm_pos":
        assert (factor >= 0).all()
    elif prior == "hmm_neg":
        assert (factor <= 0).all()


def test_side_and_model_kwargs_are_independent():
    y = torch.ones(5, 7)
    model = cEBMF(y, prior_L="hmm", prior_F="hmm", prior_L_kwargs={"maxiter": 2}, prior_F_kwargs={"maxiter": 7})
    assert model.prior_L_fn is not model.prior_F_fn
    assert model.prior_L_fn.kwargs == {"maxiter": 2}
    assert model.prior_F_fn.kwargs == {"maxiter": 7}
    cEBMF(y, prior_F="hmm", prior_F_kwargs={"maxiter": 11})
    assert model.prior_F_fn.kwargs == {"maxiter": 7}
    assert {"hmm", "hmm_pos", "hmm_neg"} <= set(PRIOR_REGISTRY.list_priors())


