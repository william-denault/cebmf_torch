def tensor(x):
    return torch.as_tensor(x, dtype=torch.float64)


@pytest.mark.parametrize("case", REFERENCE)
def test_matches_fsusie_reference(case):
    """Saved outputs generated by base R, with no Python solver involved."""
    ref = REFERENCE[case]
    inputs = {k: (v[0] if isinstance(v, list) and len(v) == 1 else v) for k, v in ref["input"].items()}
    inputs["y"], inputs["se"] = tensor(inputs["y"]), tensor(inputs["se"])
    result = fit_ash_hmm(**inputs)
    # The bounded scalar optimizer differs from R's Brent optimizer; allow
    # its numerical tolerance to propagate through one-sided mean updates.
    tolerance = 2e-6 if inputs.get("nonnegative_state_means") and inputs.get("learn_state_means", True) else 2e-9
    for field in ("post_mean", "post_mean2", "pi0_null", "lfsr", "state_probability", "history", "objective_history"):
        torch.testing.assert_close(getattr(result, field), tensor(ref[field]), atol=tolerance, rtol=tolerance)
    torch.testing.assert_close(result.log_likelihood, tensor(ref["log_likelihood"][0]), atol=tolerance, rtol=tolerance)
    for field in ("mu", "prior_sd", "transition", "init_prob", "mixture_weight"):
        torch.testing.assert_close(result.model_param[field], tensor(ref[field]), atol=tolerance, rtol=tolerance)
    assert result.state_counts == ref["state_counts"]


def test_smoother_matches_exhaustive_path_enumeration():
    """Enumerating every path independently checks orientation and endpoints."""
    emission = tensor([[0.8, 0.1], [0.2, 0.6], [0.4, 0.3], [0.1, 0.9]])
    transition = tensor([[0.85, 0.15], [0.4, 0.6]])
    init = tensor([0.2, 0.8])
    probability = torch.zeros_like(emission)
    counts = torch.zeros_like(transition)
    evidence = 0.0
    for path in itertools.product(range(2), repeat=4):
        weight = init[path[0]] * emission[0, path[0]]
        for t in range(1, 4):
            weight = weight * transition[path[t - 1], path[t]] * emission[t, path[t]]
        evidence += float(weight)
        for t, state in enumerate(path):
            probability[t, state] += weight
        for t in range(1, 4):
            counts[path[t - 1], path[t]] += weight
    for smoother in (_smooth, _log_smoother):
        ll, gamma, xi = smoother(emission.log(), transition, init)
        torch.testing.assert_close(ll, tensor(math.log(evidence)))
        torch.testing.assert_close(gamma, probability / evidence)
        torch.testing.assert_close(xi, counts / evidence)
        torch.testing.assert_close(gamma.sum(1), torch.ones(4, dtype=torch.float64))
        torch.testing.assert_close(xi.sum(), tensor(3.0))


def test_log_fallback_for_unreachable_largest_emission():
    emission = tensor([[-1000.0, 0.0], [-1001.0, 0.0]])
    ll, gamma, counts = _smooth(emission, torch.eye(2, dtype=torch.float64), tensor([1.0, 0.0]))
    torch.testing.assert_close(ll, tensor(-2001.0))
    torch.testing.assert_close(gamma, tensor([[1.0, 0.0], [1.0, 0.0]]))
    torch.testing.assert_close(counts, tensor([[1.0, 0.0], [0.0, 0.0]]))


def test_one_sided_emission_and_moments_against_numerical_integration():
    """Integrate the actual prior times likelihood, independently of formulas."""
    y, se, mu, sd = tensor([-2.0, 0.8]), tensor([0.5, 0.7]), tensor([0.4]), tensor([0.9])
    grid = torch.linspace(0, 10, 100001, dtype=torch.float64)
    normal = torch.distributions.Normal
    prior = normal(mu[0], sd[0]).log_prob(grid).exp() / normal(0, 1).cdf(mu[0] / sd[0])
    density = normal(grid, se[:, None]).log_prob(y[:, None]).exp() * prior
    marginal = torch.trapezoid(density, grid, dim=1)
    expected_mean = torch.trapezoid(density * grid, grid, dim=1) / marginal
    expected_second = torch.trapezoid(density * grid.square(), grid, dim=1) / marginal
    emission = _component_log_emission(y, se, mu, sd, True).flatten().exp()
    mean, second, _, _ = _posterior_moments(y, se, mu, sd, torch.ones(2, 1, 1, dtype=torch.float64), True)
    torch.testing.assert_close(emission, marginal, rtol=1e-6, atol=1e-10)
    torch.testing.assert_close(mean, expected_mean, rtol=1e-6, atol=1e-8)
    torch.testing.assert_close(second, expected_second, rtol=1e-6, atol=1e-8)


def test_negative_is_reflection_and_has_nonpositive_support():
    y, se = tensor([-20, -1, 0.1, 2.0, 3.0]), tensor([0.1, 0.5, 0.6, 0.4, 0.3])
    settings = {"mu": [0, 1.2, 3.4], "prior_sd": [0, 0.4, 1], "maxiter": 8, "prune_states": False}
    positive = hmm_pos_posterior_means(None, y, se, **settings)
    negative = hmm_neg_posterior_means(None, -y, se, **{**settings, "mu": [0, -1.2, -3.4]})
    assert (positive.post_mean >= 0).all() and (negative.post_mean <= 0).all()
    for field in ("post_mean2", "pi0_null", "lfsr", "loss", "state_probability"):
        torch.testing.assert_close(getattr(positive, field), getattr(negative, field))
    torch.testing.assert_close(positive.post_mean, -negative.post_mean)
    torch.testing.assert_close(positive.model_param["mu"], -negative.model_param["mu"])
    torch.testing.assert_close(positive.lfsr, positive.pi0_null)
    assert torch.isfinite(positive.post_mean2).all()
    assert (positive.post_mean2 >= positive.post_mean.square()).all()
    with pytest.raises(ValueError, match="strictly positive"):
        hmm_neg_posterior_means(None, y, se, **settings)
    with pytest.raises(ValueError, match="requires"):
        hmm_pos_posterior_means(None, y, se, nonnegative_state_means=False)


@pytest.mark.parametrize("dtype", [torch.float32, torch.float64])
def test_null_singleton_and_scalar_se(dtype):
    result = fit_ash_hmm(torch.zeros(1, dtype=dtype), tensor(0.5), mu=[0], prior_sd=[0], maxiter=2)
    assert result.post_mean.dtype == result.post_mean2.dtype == result.loss.dtype == dtype
    torch.testing.assert_close(result.post_mean, torch.zeros(1, dtype=dtype))
    torch.testing.assert_close(result.pi0_null, torch.ones(1, dtype=dtype))
    torch.testing.assert_close(result.lfsr, torch.ones(1, dtype=dtype))
    torch.testing.assert_close(result.loss, torch.tensor(math.log(0.5) + 0.5 * math.log(2 * math.pi), dtype=dtype))


def test_full_marginal_likelihood_gives_valid_kl():
    y, se = tensor([0.1, -0.1, 2.1, 1.9, 0.0]), tensor([0.3, 0.4, 0.5, 0.4, 0.3])
    result = fit_ash_hmm(y, se, maxiter=6)
    kl = normal_means_loglik(y, se, result.post_mean, result.post_mean2) + result.loss
    assert kl >= -1e-10
    torch.testing.assert_close(result.loss, -result.history[-1])


def test_lfsr_counts_zero_atom_in_both_sign_tails():
    mu, initial = tensor([0, 1, -1]), tensor([0.6, 0.1, 0.3])
    result = fit_ash_hmm(tensor([0]), tensor(1), mu=mu, prior_sd=[0], init_prob=initial, maxiter=0)
    # A single observation with three atoms: Bayes' rule gives exact weights.
    weights = initial * (-0.5 * mu.square()).exp()
    weights /= weights.sum()
    expected = weights[0] + torch.minimum(weights[1], weights[2])
    torch.testing.assert_close(result.lfsr, expected.reshape(1))
    assert result.lfsr[0] > 0.5
    assert result.lfsr[0] > result.pi0_null[0]


def test_gaussian_lfsr_retains_small_tail_probabilities():
    y = tensor([0, 10 * math.sqrt(2), -10 * math.sqrt(2)])
    result = fit_ash_hmm(
        y, tensor(1), mu=[0], prior_sd=[0, 1], init_rho=[[0, 1]], null_state="adaptive", maxiter=0
    )
    # The posterior is N(y/2, 1/2); use erfc as an independent normal-tail oracle.
    tail = 0.5 * math.erfc(10 / math.sqrt(2))
    torch.testing.assert_close(result.lfsr, tensor([0.5, tail, tail]), atol=0, rtol=1e-12)


