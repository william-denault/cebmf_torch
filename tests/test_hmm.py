def test_penalty_favors_transitions_to_zero():
    y, se = tensor([0.1, -0.3, 1.8, 1.3, -1.7, -1.1, 0.2, 0.4]), tensor(0.5)
    kwargs = {
        "mu": [0, 1.4, -1.2],
        "prior_sd": [0, 0.3, 1],
        "maxiter": 1,
        "learn_state_means": False,
        "prune_states": False,
    }
    neutral = hmm_posterior_means(None, y, se, penalty=1.0, **kwargs)
    penalized = hmm_posterior_means(None, y, se, penalty=1.5, **kwargs)
    assert (penalized.model_param["transition"][:, 0] > neutral.model_param["transition"][:, 0]).all()
    # The non-null atoms lie at nonzero centers and should not get a spike penalty.
    torch.testing.assert_close(penalized.model_param["mixture_weight"], neutral.model_param["mixture_weight"])
    torch.testing.assert_close(neutral.objective_history, neutral.history)


def test_single_adaptive_state_has_the_ash_spike_penalty():
    y, se, sd, initial = tensor([0.1, 0.2, 1.5, -0.8]), tensor(0.5), tensor([0, 1]), tensor([0.4, 0.6])
    result = fit_ash_hmm(
        y, se, mu=[0], prior_sd=sd, init_rho=initial[None], null_state="adaptive",
        penalty=1.5, maxiter=1, learn_state_means=False, prune_states=False,
    )
    component_log = torch.distributions.Normal(0, (se.square() + sd.square()).sqrt()).log_prob(y[:, None])
    counts = (component_log + initial.log()).softmax(1).sum(0) + tensor([0.5, 0])
    expected_weights = counts / counts.sum()
    torch.testing.assert_close(result.model_param["mixture_weight"][0], expected_weights)
    expected_ll = torch.logsumexp(component_log + expected_weights.log(), dim=1).sum()
    torch.testing.assert_close(result.loss, -expected_ll)
    torch.testing.assert_close(result.objective, expected_ll + 0.5 * expected_weights[0].log())


@pytest.mark.parametrize("penalty", [1.0, 1.5, 20.0])
def test_penalty_objective_and_unpenalized_loss(penalty):
    y, se = tensor([0.1, -0.3, 1.8, 1.3, -1.7, -1.1, 0.2, 0.4]), tensor([0.5] * 8)
    result = fit_ash_hmm(
        y, se, mu=[0, 1.4, -1.2], prior_sd=[0, 0.3, 1], null_state="adaptive",
        estimate_init=True, penalty=penalty, maxiter=12, learn_state_means=False, prune_states=False,
    )
    params = result.model_param
    emission = torch.logsumexp(
        _component_log_emission(y, se, params["mu"], params["prior_sd"], False) + params["mixture_weight"].log(), 2
    )
    ll, _, _ = _log_smoother(emission, params["transition"], params["init_prob"])
    log_null = params["transition"][:, 0].log().sum() + params["init_prob"][0].log()
    log_null += params["mixture_weight"][0, 0].log()
    torch.testing.assert_close(result.loss, -ll)
    torch.testing.assert_close(result.history[-1], ll)
    torch.testing.assert_close(result.objective, ll + (penalty - 1) * log_null)
    torch.testing.assert_close(result.objective_history[-1], result.objective)
    assert (result.objective_history.diff() >= -1e-9).all()
    assert normal_means_loglik(y, se, result.post_mean, result.post_mean2) + result.loss >= -1e-9


